-- --------------------------------------------------------------------------
-- Helper: updated_at maintenance
-- --------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

-- --------------------------------------------------------------------------
-- 1. signals — one row per generated signal card (journal.signals today)
--    Mirrors system/journal.py: log_signal() + daily_count cap (3/day).
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.signals (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  symbol        text NOT NULL DEFAULT 'XAUUSD'
                CHECK (symbol IN ('XAUUSD', 'EURUSD', 'GBPUSD')),
  direction     text NOT NULL CHECK (direction IN ('long', 'short')),
  entry         numeric(12, 2) NOT NULL CHECK (entry > 0),
  stop_loss     numeric(12, 2) NOT NULL CHECK (stop_loss > 0),
  tp1           numeric(12, 2) NOT NULL CHECK (tp1 > 0),
  tp2           numeric(12, 2) NOT NULL CHECK (tp2 > 0),
  confidence    integer NOT NULL CHECK (confidence BETWEEN 0 AND 100),
  -- E1 gate score at publication time (0-100, publish only >= 70).
  e1_score      integer CHECK (e1_score BETWEEN 0 AND 100),
  mode          text NOT NULL DEFAULT 'paper'
                CHECK (mode IN ('paper', 'live')),
  -- open / tp1 / tp2 / sl / expired / rejected / no_signal is NOT stored
  -- here: a rejected card never becomes a signal row.
  status        text NOT NULL DEFAULT 'open'
                CHECK (status IN ('open', 'tp1', 'tp2', 'sl', 'expired')),
  exit_price    numeric(12, 2) CHECK (exit_price > 0),
  pnl_r         numeric(8, 4),
  -- Day (UTC) the signal was generated, for the 3/day cap. Enforced in
  -- application code (journal.log_signal) AND by the unique index below
  -- on (day, daily_seq) with a check in the service layer; the cap is
  -- a business rule, the index only guarantees ordering.
  day_utc       date NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')::date,
  daily_seq     smallint NOT NULL CHECK (daily_seq BETWEEN 1 AND 3),
  chart_path    text,
  card_text     text NOT NULL,
  review_status text NOT NULL DEFAULT 'pending'
                CHECK (review_status IN ('pending', 'approved', 'rejected', 'published')),
  reviewed_at   timestamptz,
  reviewed_by   bigint,
  published_at  timestamptz,
  channel_message_id bigint,
  -- Regime snapshot at generation time (R0): trend / range / shock.
  regime        text CHECK (regime IN ('trend', 'range', 'shock')),
  atr           numeric(10, 4),
  UNIQUE (day_utc, daily_seq)
);
COMMENT ON TABLE public.signals IS 'One row per signal card. Cap: max 3 per UTC day (daily_seq 1-3). mode is paper until a live phase is approved; paper is always labelled paper in every display.';
CREATE INDEX IF NOT EXISTS signals_status_idx ON public.signals (status);
CREATE INDEX IF NOT EXISTS signals_day_idx ON public.signals (day_utc);
CREATE INDEX IF NOT EXISTS signals_symbol_created_idx ON public.signals (symbol, created_at DESC);
DROP TRIGGER IF EXISTS signals_set_updated_at ON public.signals;
CREATE TRIGGER signals_set_updated_at
  BEFORE UPDATE ON public.signals
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- --------------------------------------------------------------------------
-- 2. agent_votes — one row per agent per signal (the learning substrate)
--    Contract: analyze() -> {agent, signal +1/-1/0, confidence 0-100,
--    detail (Arabic)}. 35 agents: R0,N0,R1,R2, C1-C7, S1,S2,S3a,S3b,
--    S4a,S4b,S4c,S5a,S5b,S5c,S6,S10,S11,S12,S13, X1,X2,X3, M1,M2,M3,E1,E2,J1.
--    Routers (R0/N0/R1/R2) and judges (M1/M2/M3/E1/E2/J1) vote too, with
--    their layer recorded, so a vote is never anonymous.
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.agent_votes (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  signal_id   bigint NOT NULL REFERENCES public.signals (id) ON DELETE CASCADE,
  agent       text NOT NULL
              CHECK (agent IN (
                'R0','N0','R1','R2',
                'C1','C2','C3','C4','C5','C6','C7',
                'S1','S2','S3a','S3b','S4a','S4b','S4c',
                'S5a','S5b','S5c','S6','S10','S11','S12','S13',
                'X1','X2','X3',
                'M1','M2','M3','E1','E2','J1')),
  layer       text NOT NULL
              CHECK (layer IN ('L0-router','L1-context','L2-structure',
                               'L3-execution','L4-judgement')),
  vote        smallint NOT NULL CHECK (vote IN (-1, 0, 1)),
  confidence  integer NOT NULL CHECK (confidence BETWEEN 0 AND 100),
  detail      text NOT NULL DEFAULT '',
  -- Weight applied by M1 at arbitration time (from learned_weights).
  weight      numeric(6, 4) NOT NULL DEFAULT 0 CHECK (weight >= 0),
  -- Was this agent degraded / abstaining with a stated reason?
  degraded    boolean NOT NULL DEFAULT false,
  degrade_reason text,
  created_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (signal_id, agent)
);
COMMENT ON TABLE public.agent_votes IS 'One row per agent per signal. The learning substrate: E2 learns weights from these votes joined to settlements.pnl_r. Abstention is vote=0 with degraded=true and a reason — never a fabricated vote.';
CREATE INDEX IF NOT EXISTS agent_votes_signal_idx ON public.agent_votes (signal_id);
CREATE INDEX IF NOT EXISTS agent_votes_agent_idx ON public.agent_votes (agent, created_at DESC);

-- --------------------------------------------------------------------------
-- 3. agent_links — inter-agent relationships (the "connections between them")
--    Directed, weighted, typed edges. Learned/maintained by E2 + J1, never
--    hand-edited in production without an audit row.
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.agent_links (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  from_agent  text NOT NULL,
  to_agent    text NOT NULL,
  link_type   text NOT NULL
              CHECK (link_type IN (
                'confirms',      -- from_agent agreeing raises to_agent weight
                'contradicts',   -- disagreement is informative, not noise
                'gates',         -- from_agent can veto/block to_agent (N0, M2)
                'feeds',         -- from_agent output is to_agent input
                'correlates'     -- votes move together (watch for double-counting)
              )),
  strength    numeric(5, 4) NOT NULL DEFAULT 0
              CHECK (strength BETWEEN -1 AND 1),
  -- How the strength was derived: backtest / walk-forward / live / manual.
  source      text NOT NULL DEFAULT 'backtest'
              CHECK (source IN ('backtest', 'walk-forward', 'live', 'manual')),
  sample_n    integer NOT NULL DEFAULT 0 CHECK (sample_n >= 0),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  updated_by  text NOT NULL DEFAULT 'E2',
  UNIQUE (from_agent, to_agent, link_type),
  CHECK (from_agent <> to_agent)
);
COMMENT ON TABLE public.agent_links IS 'Directed weighted edges between agents. M1 must not double-count two agents linked with correlates/strength near 1 — E2 shrinks their combined weight.';
CREATE INDEX IF NOT EXISTS agent_links_from_idx ON public.agent_links (from_agent);
CREATE INDEX IF NOT EXISTS agent_links_to_idx ON public.agent_links (to_agent);
DROP TRIGGER IF EXISTS agent_links_set_updated_at ON public.agent_links;
CREATE TRIGGER agent_links_set_updated_at
  BEFORE UPDATE ON public.agent_links
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

