-- --------------------------------------------------------------------------
-- 13. learned_weights_history — E2 optimiser output over time
--     One row per agent per optimisation run. The live weights are the
--     latest run; history is what makes learning auditable.
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.learned_weights_history (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_at      timestamptz NOT NULL DEFAULT now(),
  run_kind    text NOT NULL CHECK (run_kind IN ('backtest', 'walk-forward', 'live')),
  agent       text NOT NULL,
  weight      numeric(6, 4) NOT NULL CHECK (weight >= 0),
  -- R-expectancy with shrinkage score * n/(n+20), as in E2 v2.
  r_expectancy numeric(8, 4),
  sample_n    integer NOT NULL DEFAULT 0 CHECK (sample_n >= 0),
  t_stat      numeric(8, 4),
  notes       text NOT NULL DEFAULT ''
);
COMMENT ON TABLE public.learned_weights_history IS 'E2 output history. A weight change without a run_kind, sample_n and t_stat is not trusted. The current published strategy has no proven edge (latest walk-forward t-stat +0.75) — that fact lives here, not hidden.';
CREATE INDEX IF NOT EXISTS learned_weights_run_idx ON public.learned_weights_history (run_at DESC, agent);

